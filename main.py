#!/usr/bin/env python3
"""
make.fun news-image-20261124 entry
Generates a deterministic news summary image for 24 November 2026.
"""
import os
import hashlib
from PIL import Image, ImageDraw, ImageFont
import textwrap

def generate_image(output_path: str) -> None:
    """Generate a deterministic news summary image."""
    # Fixed seed for deterministic output
    seed = "2026-11-24-world-news-summary"
    hash_obj = hashlib.sha256(seed.encode())
    color_seed = int(hash_obj.hexdigest()[:8], 16)
    
    # Deterministic colors from seed
    bg_color = (
        (color_seed >> 16) & 0xFF,
        (color_seed >> 8) & 0xFF,
        color_seed & 0xFF
    )
    # Ensure readable contrast
    bg_color = (max(40, min(80, bg_color[0])), max(40, min(80, bg_color[1])), max(40, min(80, bg_color[2])))
    text_color = (255 - bg_color[0], 255 - bg_color[1], 255 - bg_color[2])
    accent_color = (255, 215, 0)  # Gold
    
    # Create image
    width, height = 1024, 1024
    img = Image.new('RGB', (width, height), bg_color)
    draw = ImageDraw.Draw(img)
    
    # Try to use default font
    try:
        font_large = ImageFont.truetype("arial.ttf", 48)
        font_medium = ImageFont.truetype("arial.ttf", 32)
        font_small = ImageFont.truetype("arial.ttf", 24)
    except:
        font_large = ImageFont.load_default()
        font_medium = ImageFont.load_default()
        font_small = ImageFont.load_default()
    
    # Draw header
    header = "WORLD NEWS SUMMARY"
    header_bbox = draw.textbbox((0, 0), header, font=font_large)
    header_width = header_bbox[2] - header_bbox[0]
    draw.text(((width - header_width) // 2, 60), header, fill=accent_color, font=font_large)
    
    # Date
    date_text = "24 November 2026"
    date_bbox = draw.textbbox((0, 0), date_text, font=font_medium)
    date_width = date_bbox[2] - date_bbox[0]
    draw.text(((width - date_width) // 2, 130), date_text, fill=text_color, font=font_medium)
    
    # Divider
    draw.line([(100, 190), (width - 100, 190)], fill=accent_color, width=3)
    
    # News items (deterministic placeholder content)
    news_items = [
        ("GEOPOLITICS", "UN Security Council convenes emergency session on regional tensions"),
        ("ECONOMY", "Global markets react to central bank policy coordination announcement"),
        ("TECHNOLOGY", "Major AI governance framework adopted by G20 nations"),
        ("CLIMATE", "COP31 preparatory talks advance loss-and-damage fund mechanisms"),
        ("HEALTH", "WHO declares progress on pandemic preparedness treaty negotiations"),
        ("SPACE", "Artemis IV mission clears critical design review for lunar gateway"),
    ]
    
    y_pos = 220
    for category, headline in news_items:
        # Category badge
        draw.rectangle([100, y_pos, 100 + 180, y_pos + 40], fill=accent_color)
        draw.text((110, y_pos + 5), category, fill=(0, 0, 0), font=font_small)
        
        # Headline
        draw.text((300, y_pos + 5), headline, fill=text_color, font=font_medium)
        y_pos += 60
    
    # Footer
    draw.line([(100, y_pos + 20), (width - 100, y_pos + 20)], fill=accent_color, width=2)
    footer = "Generated by make.fun agent  •  Deterministic output  •  1024x1024 PNG"
    footer_bbox = draw.textbbox((0, 0), footer, font=font_small)
    footer_width = footer_bbox[2] - footer_bbox[0]
    draw.text(((width - footer_width) // 2, y_pos + 40), footer, fill=(180, 180, 180), font=font_small)
    
    # QR code placeholder (deterministic)
    qr_size = 120
    qr_x = width - qr_size - 40
    qr_y = height - qr_size - 40
    draw.rectangle([qr_x, qr_y, qr_x + qr_size, qr_y + qr_size], fill=(60, 60, 60))
    draw.text((qr_x + 10, qr_y + qr_size // 2 - 10), "make.fun", fill=(200, 200, 200), font=font_small)
    
    # Save
    img.save(output_path, format='PNG', optimize=True)
    print(f"Image saved to {output_path}")

def main():
    output_path = os.path.join(os.path.dirname(__file__), 'output', 'entry.png')
    generate_image(output_path)
    
    # Verify deterministic output by hashing
    with open(output_path, 'rb') as f:
        content = f.read()
    sha256 = hashlib.sha256(content).hexdigest()
    print(f"SHA256: {sha256}")
    print(f"Size: {len(content)} bytes")

if __name__ == '__main__':
    main()